def images_for(name):
    """[Start, Ende] als URL-Pfade, oder [] wenn es zur Uebung keine (vollstaendigen) Bilder gibt."""
    slug = SLUGS.get(name)
    if not slug:
        return []
    files = [f"{slug}-{i}.webp" for i in (0, 1)]
    return [f"/img/ex/{f}" for f in files] if all((IMG_DIR / f).is_file() for f in files) else []
